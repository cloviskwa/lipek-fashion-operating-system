#!/usr/bin/env node
/**
 * Regenerate docs/implementation/repo-manifest.json and, with --inject, refresh the
 * manifest table embedded in docs/implementation/ROCKET_NEW_BUILD_BRIEF.md Appendix A.
 *
 * Usage:
 *   node scripts/generate-manifest.mjs           # write repo-manifest.json
 *   node scripts/generate-manifest.mjs --inject  # also refresh the brief's Appendix A table
 *   node scripts/generate-manifest.mjs --markdown # print the table to stdout, write nothing
 *
 * The manifest is generated, never hand-edited. Run it after any commit that adds,
 * removes or changes a project file, otherwise verify-manifest.mjs will (correctly) fail.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { buildManifest, EXCLUDED, MANIFEST_PATH, REPO_ROOT } from './manifest-lib.mjs';

const BRIEF_PATH = path.join(REPO_ROOT, 'docs/implementation/ROCKET_NEW_BUILD_BRIEF.md');
const SECTIONS = [
  { begin: '<!-- BEGIN:repo-manifest -->', end: '<!-- END:repo-manifest -->', render: toMarkdown },
  { begin: '<!-- BEGIN:repo-tree -->', end: '<!-- END:repo-tree -->', render: toTree },
];

function toMarkdown(manifest) {
  const lines = [
    `_Generated by \`node scripts/generate-manifest.mjs\`. ${manifest.fileCount} files, ${manifest.totalBytes.toLocaleString('en-US')} bytes._`,
    '',
    `_Excluded (self-referential): ${EXCLUDED.map((p) => `\`${p}\``).join(', ')}._`,
    '',
    '| # | Path | Bytes | SHA-256 |',
    '| --- | --- | --- | --- |',
  ];
  manifest.files.forEach((f, i) => {
    lines.push(`| ${i + 1} | \`${f.path}\` | ${f.bytes} | \`${f.sha256}\` |`);
  });
  return lines.join('\n');
}

const NEWLINE = String.fromCharCode(10);

function toTree(manifest) {
  /** @type {Map<string, {files: number, children: Set<string>}>} */
  const dirs = new Map();
  const ensure = (dir) => {
    if (!dirs.has(dir)) dirs.set(dir, { files: 0, children: new Set() });
    return dirs.get(dir);
  };
  ensure('.');
  for (const { path: relPath } of manifest.files) {
    const parts = relPath.split('/');
    const fileName = parts.pop();
    let parent = '.';
    for (const part of parts) {
      const dir = parent === '.' ? part : `${parent}/${part}`;
      ensure(parent).children.add(dir);
      ensure(dir);
      parent = dir;
    }
    ensure(parent).files += 1;
    void fileName;
  }

  const lines = ['```text', 'lipek-platform/'];
  const walk = (dir, prefix) => {
    const children = [...dirs.get(dir).children].sort();
    children.forEach((child, index) => {
      const last = index === children.length - 1;
      const name = child.slice(child.lastIndexOf('/') + 1);
      const count = dirs.get(child).files;
      const label = count > 0 ? `${name}/  (${count} file${count === 1 ? '' : 's'})` : `${name}/`;
      lines.push(`${prefix}${last ? '`-- ' : '|-- '}${label}`);
      walk(child, `${prefix}${last ? '    ' : '|   '}`);
    });
  };
  walk('.', '');
  const rootFiles = dirs.get('.').files;
  lines.push(`(+ ${rootFiles} files at the repository root)`);
  lines.push('```');
  return lines.join(NEWLINE);
}

const args = new Set(process.argv.slice(2));
const manifest = buildManifest();
const markdown = toMarkdown(manifest);

if (args.has('--markdown')) {
  process.stdout.write(`${markdown}\n`);
  process.exit(0);
}

writeFileSync(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
console.log(`Wrote ${path.relative(REPO_ROOT, MANIFEST_PATH)} (${manifest.fileCount} files).`);

if (args.has('--inject')) {
  let brief = readFileSync(BRIEF_PATH, 'utf8');
  for (const { begin, end, render } of SECTIONS) {
    const from = brief.indexOf(begin);
    const to = brief.indexOf(end);
    if (from === -1 || to === -1 || to < from) {
      console.error(
        `Could not find ${begin} / ${end} markers in ${path.relative(REPO_ROOT, BRIEF_PATH)}.`,
      );
      process.exit(1);
    }
    brief = `${brief.slice(0, from + begin.length)}

${render(manifest)}

${brief.slice(to)}`;
  }
  writeFileSync(BRIEF_PATH, brief, 'utf8');
  console.log(
    `Injected manifest table and directory tree into ${path.relative(REPO_ROOT, BRIEF_PATH)}.`,
  );
}
